/// Verifies an ML-DSA-65 signature over `checksums_bytes` against the embedded
/// public key. Never panics on malformed input.
pub fn verify_signature(checksums_bytes: &[u8], signature_bytes: &[u8]) -> bool {
    verify_signature_with_key(&PUBLIC_KEY_BYTES, checksums_bytes, signature_bytes)
}

fn verify_signature_with_key(
    public_key_bytes: &[u8; 1952],
    checksums_bytes: &[u8],
    signature_bytes: &[u8],
) -> bool {
    let Ok(verifying_key) = VerifyingKey::<MlDsa65>::new_from_slice(public_key_bytes.as_slice())
    else {
        return false;
    };
    let Ok(sig) = Signature::<MlDsa65>::try_from(signature_bytes) else {
        return false;
    };
    verifying_key.verify(checksums_bytes, &sig).is_ok()
}

/// Parses a `sha256sum`-format checksums file (`<hash>  <filename>` per line) and
/// returns the hash for `filename`, or `None` if not listed.
pub fn find_checksum<'a>(checksums_text: &'a str, filename: &str) -> Option<&'a str> {
    checksums_text.lines().find_map(|line| {
        let (hash, rest) = line.split_once(char::is_whitespace)?;
        (rest.trim_start().trim_start_matches('*') == filename).then_some(hash)
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use ml_dsa::{Generate, KeyExport, Keypair, SignatureEncoding, Signer, SigningKey};

    /// A throwaway test ML-DSA keypair -- NOT the real signing key. Tests sign
    /// with this key and verify against a matching test *public* key (passed
    /// explicitly, bypassing the embedded real PUBLIC_KEY_BYTES), proving the
    /// verification logic itself is correct without ever touching the real key.
    fn test_keypair() -> (SigningKey<MlDsa65>, [u8; 1952]) {
        let sk = SigningKey::<MlDsa65>::generate();
        let vk_bytes: [u8; 1952] = sk
            .verifying_key()
            .to_bytes()
            .as_slice()
            .try_into()
            .expect("verifying key is always 1952 bytes for MlDsa65");
        (sk, vk_bytes)
    }

    #[test]
    fn valid_signature_is_accepted() {
        let (sk, vk_bytes) = test_keypair();
        let msg = b"checksums content";
        let sig = sk.sign(msg);
        assert!(verify_signature_with_key(
            &vk_bytes,
            msg,
            sig.to_bytes().as_ref()
        ));
    }

    #[test]
    fn tampered_checksums_content_is_rejected() {
        let (sk, vk_bytes) = test_keypair();
        let sig = sk.sign(b"checksums content");
        assert!(!verify_signature_with_key(
            &vk_bytes,
            b"tampered content",
            sig.to_bytes().as_ref()
        ));
    }

    #[test]
    fn signature_from_wrong_key_is_rejected() {
        let (sk_a, _) = test_keypair();
        let (_, vk_bytes_b) = test_keypair();
        let msg = b"checksums content";
        let sig = sk_a.sign(msg);
        assert!(!verify_signature_with_key(
            &vk_bytes_b,
            msg,
            sig.to_bytes().as_ref()
        ));
    }

    #[test]
    fn malformed_signature_is_rejected_without_panic() {
        let (_, vk_bytes) = test_keypair();
        assert!(!verify_signature_with_key(
            &vk_bytes,
            b"anything",
            b"not-a-real-signature"
        ));
    }

    #[test]
    fn empty_signature_is_rejected_without_panic() {
        let (_, vk_bytes) = test_keypair();
        assert!(!verify_signature_with_key(&vk_bytes, b"anything", b""));
    }

    #[test]
    fn find_checksum_locates_matching_filename() {
        let checksums = "abc123  file-a.tar.gz\ndef456  file-b.zip\n";
        assert_eq!(find_checksum(checksums, "file-a.tar.gz"), Some("abc123"));
        assert_eq!(find_checksum(checksums, "file-b.zip"), Some("def456"));
    }

    #[test]
    fn find_checksum_returns_none_for_missing_filename() {
        let checksums = "abc123  file-a.tar.gz\n";
        assert_eq!(find_checksum(checksums, "nonexistent.zip"), None);
    }
}
